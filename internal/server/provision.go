var wgWhitespace = strings.NewReplacer(" ", "", "\t", "", "\r", "", "\v", "", "\f", "")

// maintenanceCommands lists the root commands of neodse-server in the order --help shows them.
var maintenanceCommands = []struct{ name, summary string }{
	{"bootstrap", "Create the controller configuration, keys and encrypted database"},
	{"unlock", "Unlock the controller database after every start"},
	{"change-passphrase", "Replace the database passphrase"},
	{"provision-agent", "Enroll a display from its provisioning request"},
	{"remove-agent", "Remove a display and its WireGuard peer"},
	{"recover-admin", "Issue a new administrator token"},
	{"renew-certificate", "Replace the generated HTTPS certificate"},
}

// isProvisionCommand reports whether name selects a root maintenance command instead of the service.
func isProvisionCommand(name string) bool {
	for _, command := range maintenanceCommands {
		if command.name == name {
			return true
		}
	}
	return false
}

// runProvisionCommand dispatches the explicit controller provisioning subcommands.
func runProvisionCommand(ctx context.Context, args []string) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	if len(args) == 0 {
		return errors.New("provisioning command is required")
	}
	if err := requireRoot(os.Geteuid(), args[0]); err != nil {
		return err
	}
	switch args[0] {
	case "bootstrap":
		return bootstrapServer(ctx, args[1:])
	case "renew-certificate":
		return renewServerCertificate(args[1:])
	case "provision-agent":
		return provisionAgent(ctx, args[1:])
	case "remove-agent":
		return removeProvisionedAgent(ctx, args[1:])
	case "recover-admin":
		return recoverAdministrator(ctx, args[1:])
	case "unlock":
		return unlockController(ctx, args[1:])
	case "change-passphrase":
		return changeDatabasePassphrase(ctx, args[1:])
	default:
		return fmt.Errorf("unknown server command %q", args[0])
	}
}

// requireRoot names the command and the privilege it needs. Configuration,
// state and the unlock socket are private, so an unprivileged command would
// otherwise fail later with a misleading missing-file or not-waiting error.
func requireRoot(uid int, command string) error {
	if uid != 0 {
		return fmt.Errorf("neodse-server %s must run as root; run it with sudo", command)
	}
	return nil
}

// renewServerCertificate replaces the configured HTTPS key pair with a new
// certificate generated by neodse-server. Without --address it keeps the IPv4
// addresses of the current certificate; --address replaces them with one address.
func renewServerCertificate(args []string) error {
	configPath, addressValue := config.DefaultServerPath, ""
	flags := flag.NewFlagSet("renew-certificate", flag.ContinueOnError)
	flags.StringVar(&configPath, "config", configPath, "server configuration path")
	flags.StringVar(&addressValue, "address", addressValue, "controller IPv4 address included in the certificate (default: keep the current certificate's addresses)")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 {
		return errors.New("renew-certificate accepts no positional arguments")
	}
	var addresses []net.IP
	if addressValue != "" {
		parsedAddress, parseErr := netip.ParseAddr(addressValue)
		if parseErr != nil || !parsedAddress.Is4() || parsedAddress.IsUnspecified() || parsedAddress.IsMulticast() {
			return errors.New("--address must be a unicast IPv4 address")
		}
		// Loopback is always included for the local proxy.
		if parsedAddress != netip.AddrFrom4([4]byte{127, 0, 0, 1}) {
			addresses = []net.IP{net.IP(parsedAddress.AsSlice())}
		}
	}
	loaded, err := config.LoadServer(configPath)
	if err != nil {
		return fmt.Errorf("load server configuration: %w", err)
	}
	if addressValue == "" {
		if addresses, err = renewableCertificateAddresses(loaded.Server.TLSCert); err != nil {
			return fmt.Errorf("current HTTPS certificate: %w", err)
		}
	}
	if err := writeServerCertificate(loaded.Server.TLSCert, loaded.Server.TLSKey, addresses); err != nil {
		return fmt.Errorf("renew HTTPS certificate: %w", err)
	}
	fmt.Fprintf(os.Stderr, "> HTTPS certificate renewed until %s; restart neodse-server and neodse-proxy, then distribute the new certificate to API clients.\n",
		time.Now().UTC().AddDate(serverCertificateYears, 0, 0).Format(time.DateOnly))
	return nil
}

// renewableCertificateAddresses returns the non-loopback IPv4 addresses of a
// certificate generated by neodse-server. Other certificates belong to an
// organizational CA and are renewed there, so they are not replaced implicitly.
func renewableCertificateAddresses(path string) ([]net.IP, error) {
	contents, err := provisioning.ReadBoundedFile(path, 1<<20)
	if err != nil {
		return nil, err
	}
	block, _ := pem.Decode(contents)
	if block == nil || block.Type != "CERTIFICATE" {
		return nil, errors.New("certificate PEM is invalid")
	}
	certificate, err := x509.ParseCertificate(block.Bytes)
	if err != nil {
		return nil, err
	}
	if certificate.Subject.CommonName != serverCertificateCommonName || certificate.Issuer.CommonName != serverCertificateCommonName {
		return nil, errors.New("certificate was not generated by neodse-server; renew it with its issuing CA, or pass --address to replace it")
	}
	var addresses []net.IP
	for _, address := range certificate.IPAddresses {
		if ipv4 := address.To4(); ipv4 != nil && !ipv4.Equal(net.IPv4(127, 0, 0, 1)) {
			addresses = append(addresses, ipv4)
		}
	}
	return addresses, nil
}

// provisionAgent validates an operator request and atomically adds database and WireGuard authority.
func provisionAgent(ctx context.Context, args []string) error {
	options, err := parseAgentProvisionOptions(args)
	if err != nil {
		return err
	}
	loaded, err := config.LoadServer(options.configPath)
	if err != nil {
		return err
	}
	server := newServer(loaded, "provisioning")
	if err := server.openMaintenanceDatabase(ctx, os.Stdin, os.Stderr); err != nil {
		return err
	}
	defer closeProvisioningDatabase(server)
	fmt.Fprintln(os.Stderr, "> Paste the client provisioning block, then press ENTER on an empty line.")
	values, err := provisioning.ReadBlock(ctx, os.Stdin)
	if err != nil {
		return err
	}
	request, err := provisioning.ParseAgentRequest(values)
	if err != nil {
		return err
	}
	lock, err := provisioning.LockDirectory("/etc/wireguard")
	if err != nil {
		return err
	}
	defer lock.Close()
	plan, err := prepareAgentProvisioning(server, options, request)
	if err != nil {
		return err
	}
	if err := commitAgentProvisioning(server, options, plan); err != nil {
		return err
	}
	fmt.Fprint(os.Stderr, "\n========================================\nCOPY TO CLIENT\n========================================\n\n")
	return provisioning.WriteServerResponse(os.Stdout, plan.response)
}

type agentProvisionOptions struct {
	configPath      string
	proxyConfigPath string
	instance        string
	endpoint        string
	force           bool
}

type agentProvisionPlan struct {
	request       provisioning.AgentRequest
	wireGuardPath string
	originalWG    []byte
	nextWG        []byte
	response      provisioning.ServerResponse
}

// parseAgentProvisionOptions validates controller enrollment flags before opening authority state.
func parseAgentProvisionOptions(args []string) (agentProvisionOptions, error) {
	options := agentProvisionOptions{configPath: config.DefaultServerPath, proxyConfigPath: config.DefaultProxyPath, instance: "neodse"}
	flags := flag.NewFlagSet("provision-agent", flag.ContinueOnError)
	flags.StringVar(&options.configPath, "config", options.configPath, "server configuration path")
	flags.StringVar(&options.proxyConfigPath, "proxy-config", options.proxyConfigPath, "proxy configuration path")
	flags.StringVar(&options.instance, "instance", options.instance, "WireGuard instance")
	flags.StringVar(&options.endpoint, "server-endpoint", "", "public WireGuard endpoint")
	flags.BoolVar(&options.force, "force", false, "replace an existing agent")
	if err := flags.Parse(args); err != nil {
		return options, err
	}
	if flags.NArg() != 0 {
		return options, errors.New("provision-agent accepts no positional arguments")
	}
	if !config.ValidInterfaceName(options.instance) {
		return options, errors.New("invalid WireGuard interface name")
	}
	return options, nil
}

// prepareAgentProvisioning derives credentials, addresses, peer configuration, and client response.
func prepareAgentProvisioning(server *Server, options agentProvisionOptions, request provisioning.AgentRequest) (agentProvisionPlan, error) {
	wireGuardPath := filepath.Join("/etc/wireguard", options.instance+".conf")
	contents, err := provisioning.ReadWireGuardConfig(options.instance)
	if err != nil {
		return agentProvisionPlan{}, err
	}
	storeContext, cancel := boundedStoreContext()
	defer cancel()
	hadOld, err := server.store.AgentExists(storeContext, request.AgentID)
	if err != nil {
		return agentProvisionPlan{}, fmt.Errorf("inspect existing agent: %w", err)
	}
	if hadOld && !options.force {
		return agentProvisionPlan{}, fmt.Errorf("agent %s already exists; use --force", request.AgentID)
	}
	next, err := removeWGPeer(string(contents), request.AgentID)
	if err != nil {
		return agentProvisionPlan{}, err
	}
	fields := parseWGFields(next)
	endpoint := options.endpoint
	if endpoint == "" {
		endpoint = wireGuardMetadata(string(contents), "NeoDSEEndpoint")
	}
	if endpoint == "" {
		return agentProvisionPlan{}, errors.New("server endpoint is not recorded in the WireGuard configuration; provide --server-endpoint")
	}
	if err := provisioning.ValidateServerEndpoint(endpoint); err != nil {
		return agentProvisionPlan{}, fmt.Errorf("server endpoint: %w", err)
	}
	privateKey, address, err := wireGuardServerIdentity(fields)
	if err != nil {
		return agentProvisionPlan{}, err
	}
	serverIP, network, err := net.ParseCIDR(address)
	if err != nil || serverIP.To4() == nil {
		return agentProvisionPlan{}, errors.New("WireGuard server Address must be IPv4 CIDR")
	}
	proxyConfig, err := config.LoadProxy(options.proxyConfigPath)
	if err != nil {
		return agentProvisionPlan{}, fmt.Errorf("load proxy configuration: %w", err)
	}
	transportURL, proxyURL, err := agentServiceURLs(serverIP, server.config.Server.TransportURL, proxyConfig.Proxy.Listen)
	if err != nil {
		return agentProvisionPlan{}, err
	}
	publicKey, err := enrollmentPublicKey(privateKey, request.WireGuardPublicKey, fields["publickey"], wireGuardPublicKey)
	if err != nil {
		return agentProvisionPlan{}, err
	}
	wgPSK, err := provisioning.Run("", "wg", "genpsk")
	if err != nil {
		return agentProvisionPlan{}, err
	}
	agentPSK, err := provisioning.RandomPSK()
	if err != nil {
		return agentProvisionPlan{}, err
	}
	agentIP, err := nextAgentIP(network, serverIP, fields["allowedips"])
	if err != nil {
		return agentProvisionPlan{}, err
	}
	next += fmt.Sprintf(
		"\n# NeoDSEAgentBegin = %s\n[Peer]\nPublicKey = %s\nPresharedKey = %s\nAllowedIPs = %s/32\n# NeoDSEAgentEnd = %s\n",
		request.AgentID, request.WireGuardPublicKey, wgPSK, agentIP, request.AgentID,
	)
	response := provisioning.ServerResponse{ServerPublicKey: publicKey, PresharedKey: wgPSK, ServerEndpoint: endpoint, ServerAddress: serverIP.String(), TransportURL: transportURL, ProxyURL: proxyURL, AgentAddress: agentIP.String(), AgentPSK: agentPSK}
	if _, err := provisioning.ValidateServerResponse(response); err != nil {
		return agentProvisionPlan{}, fmt.Errorf("invalid generated provisioning response: %w", err)
	}
	return agentProvisionPlan{request: request, wireGuardPath: wireGuardPath, originalWG: contents, nextWG: []byte(next), response: response}, nil
}

// wireGuardServerIdentity requires an unambiguous interface identity for enrollment.
func wireGuardServerIdentity(fields map[string][]string) (string, string, error) {
	if len(fields["privatekey"]) > 1 {
		return "", "", errors.New("WireGuard server configuration contains multiple PrivateKey values; keep exactly one PrivateKey in [Interface]")
	}
	privateKey, address := first(fields["privatekey"]), first(fields["address"])
	if privateKey == "" || address == "" {
		return "", "", errors.New("WireGuard server configuration is missing PrivateKey or Address")
	}
	return privateKey, address, nil
}

// wireGuardPublicKey derives the public key of a WireGuard private key.
func wireGuardPublicKey(privateKey string) (string, error) {
	return provisioning.Run(privateKey+"\n", "wg", "pubkey")
}

// enrollmentPublicKey returns the controller public key only for an agent key
// that cannot replace another peer's routes and credentials, so the response
// cannot be built without this check. WireGuard identifies a peer by its public
// key, and silently ignores a peer whose key matches the interface's own key.
// The caller has already removed this agent's old block, allowing reenrollment.
// Production passes wireGuardPublicKey as derive; tests supply a fixed key.
func enrollmentPublicKey(privateKey, agentKey string, peerKeys []string, derive func(string) (string, error)) (string, error) {
	serverKey, err := derive(privateKey)
	if err != nil {
		return "", err
	}
	if agentKey == serverKey {
		return "", errors.New("agent WireGuard public key must differ from the controller public key")
	}
	if slices.Contains(peerKeys, agentKey) {
		return "", errors.New("agent WireGuard public key already belongs to another peer")
	}
	return serverKey, nil
}

// agentServiceURLs derives the transport and proxy endpoints given to a display
// from the controller's configured listeners, which displays reach at the
// controller's WireGuard address.
func agentServiceURLs(serverIP net.IP, transportURL, proxyListen string) (string, string, error) {
	parsed, err := url.Parse(transportURL)
	if err != nil || parsed.Port() == "" || !net.ParseIP(parsed.Hostname()).Equal(serverIP) {
		return "", "", fmt.Errorf("server.transport_url must use the WireGuard address %s", serverIP)
	}
	proxyHost, proxyPort, err := net.SplitHostPort(proxyListen)
	if err != nil || !net.ParseIP(proxyHost).Equal(serverIP) {
		return "", "", fmt.Errorf("proxy.listen must use the WireGuard address %s", serverIP)
	}
	host := serverIP.String()
	return "ws://" + net.JoinHostPort(host, parsed.Port()), "http://" + net.JoinHostPort(host, proxyPort), nil
}

// commitAgentProvisioning activates WireGuard state before committing matching database authority.
func commitAgentProvisioning(server *Server, options agentProvisionOptions, plan agentProvisionPlan) error {
	if err := applyWireGuardConfiguration(options.instance, plan.wireGuardPath, plan.originalWG, plan.nextWG); err != nil {
		return err
	}
	if err := server.createAgentCredential(plan.request.AgentID, plan.response.AgentPSK, plan.response.AgentAddress, options.force); err != nil {
		if restoreErr := restoreWireGuardConfiguration(options.instance, plan.wireGuardPath, plan.originalWG); restoreErr != nil {
			return fmt.Errorf("persist agent credential: %v; restore WireGuard configuration: %w", err, restoreErr)
		}
		return err
	}
	return nil
}

// removeProvisionedAgent removes database authority and its managed WireGuard peer together.
func removeProvisionedAgent(ctx context.Context, args []string) error {
	flags := flag.NewFlagSet("remove-agent", flag.ContinueOnError)
	configPath, instance := config.DefaultServerPath, "neodse"
	flags.StringVar(&configPath, "config", configPath, "server configuration path")
	flags.StringVar(&instance, "instance", instance, "WireGuard instance")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if !config.ValidInterfaceName(instance) {
		return errors.New("invalid WireGuard interface name")
	}
	if flags.NArg() != 1 || !identity.ValidAgentID(flags.Arg(0)) {
		return errors.New("one valid agent ID is required")
	}
	loaded, err := config.LoadServer(configPath)
	if err != nil {
		return err
	}
	s := newServer(loaded, "provisioning")
	if err := s.openMaintenanceDatabase(ctx, os.Stdin, os.Stderr); err != nil {
		return err
	}
	defer closeProvisioningDatabase(s)
	lock, err := provisioning.LockDirectory("/etc/wireguard")
	if err != nil {
		return err
	}
	defer lock.Close()
	wgPath := filepath.Join("/etc/wireguard", instance+".conf")
	b, err := provisioning.ReadWireGuardConfig(instance)
	if err != nil {
		return err
	}
	next, err := removeWGPeer(string(b), flags.Arg(0))
	if err != nil {
		return err
	}
	if err := applyWireGuardConfiguration(instance, wgPath, b, []byte(next)); err != nil {
		return err
	}
	if err := s.deleteAgentCredential(flags.Arg(0)); err != nil {
		if restoreErr := restoreWireGuardConfiguration(instance, wgPath, b); restoreErr != nil {
			return fmt.Errorf("remove agent credential: %v; restore WireGuard configuration: %w", err, restoreErr)
		}
		return err
	}
	return nil
}

// applyWireGuardConfiguration writes and activates a complete validated WireGuard configuration.
func applyWireGuardConfiguration(instance, path string, current, next []byte) error {
	if err := provisioning.AtomicWriteWithRollback(path, current, next, 0o600); err != nil {
		return err
	}
	stripped, err := provisioning.Run("", "wg-quick", "strip", instance)
	if err == nil {
		_, err = provisioning.Run(stripped+"\n", "wg", "syncconf", instance, "/dev/stdin")
	}
	if err == nil {
		return nil
	}
	if restoreErr := restoreWireGuardConfiguration(instance, path, current); restoreErr != nil {
		return fmt.Errorf("apply WireGuard configuration: %v; restore configuration: %w", err, restoreErr)
	}
	return fmt.Errorf("apply WireGuard configuration: %w", err)
}

// restoreWireGuardConfiguration rolls back both the durable file and active interface state.
func restoreWireGuardConfiguration(instance, path string, contents []byte) error {
	if err := provisioning.AtomicWrite(path, contents, 0o600); err != nil {
		return err
	}
	stripped, err := provisioning.Run("", "wg-quick", "strip", instance)
	if err != nil {
		return err
	}
	_, err = provisioning.Run(stripped+"\n", "wg", "syncconf", instance, "/dev/stdin")
	return err
}

// parseWGFields follows WireGuard's case-insensitive keys and ASCII whitespace handling.
func parseWGFields(contents string) map[string][]string {
	result := map[string][]string{}
	for line := range strings.SplitSeq(contents, "\n") {
		line, _, _ = strings.Cut(line, "#")
		key, value, ok := strings.Cut(wgWhitespace.Replace(line), "=")
		if ok && key != "" && value != "" {
			key = strings.ToLower(key)
			result[key] = append(result[key], value)
		}
	}
	return result
}

// wireGuardMetadata extracts one NeoDSE-managed comment value.
func wireGuardMetadata(contents, key string) string {
	prefix := "# " + key + " ="
	for line := range strings.SplitSeq(contents, "\n") {
		if value, ok := strings.CutPrefix(strings.TrimSpace(line), prefix); ok {
			return strings.TrimSpace(value)
		}
	}
	return ""
}

// first returns the first collected field value or an empty string.
func first(v []string) string {
	if len(v) == 0 {
		return ""
	}
	return v[0]
}

// nextAgentIP selects the first free non-server, non-network, non-broadcast IPv4 address.
func nextAgentIP(network *net.IPNet, server net.IP, used []string) (net.IP, error) {
	if network == nil || network.IP.To4() == nil || server.To4() == nil || !network.Contains(server) {
		return nil, errors.New("invalid WireGuard IPv4 subnet")
	}
	ones, bits := network.Mask.Size()
	if bits != 32 || ones > 30 {
		return nil, errors.New("WireGuard subnet has no available agent address")
	}
	type addressRange struct{ first, last uint64 }
	serverAddress := uint64(binary.BigEndian.Uint32(server.To4()))
	reserved := []addressRange{{serverAddress, serverAddress}}
	for _, value := range used {
		for raw := range strings.SplitSeq(value, ",") {
			prefix, err := netip.ParsePrefix(strings.TrimSpace(raw))
			if err != nil {
				address, addressErr := netip.ParseAddr(strings.TrimSpace(raw))
				if addressErr != nil {
					return nil, errors.New("WireGuard peer contains invalid AllowedIPs")
				}
				prefix = netip.PrefixFrom(address, address.BitLen())
			}
			if !prefix.Addr().Is4() {
				continue
			}
			address := prefix.Masked().Addr().As4()
			first := uint64(binary.BigEndian.Uint32(address[:]))
			reserved = append(reserved, addressRange{first, first + (uint64(1) << (32 - prefix.Bits())) - 1})
		}
	}
	// Skip whole reserved ranges, including overlapping routes. Counting every
	// address can hang on large subnets and wrapping IPv4 arithmetic.
	sort.Slice(reserved, func(i, j int) bool { return reserved[i].first < reserved[j].first })
	base := uint64(binary.BigEndian.Uint32(network.IP.Mask(network.Mask).To4()))
	broadcast := base + (uint64(1) << (32 - ones)) - 1
	candidate := base + 1
	for _, block := range reserved {
		if block.first > candidate {
			break
		}
		if block.last >= candidate {
			candidate = block.last + 1
		}
	}
	if candidate >= broadcast || candidate > math.MaxUint32 {
		return nil, errors.New("WireGuard subnet has no available agent address")
	}
	address := make(net.IP, net.IPv4len)
	binary.BigEndian.PutUint32(address, uint32(candidate))
	return address, nil
}

// recoverAdministrator restores API administration from the controller host
// when every administrator token has been lost, disabled or has expired. The
// named account becomes an enabled, non-expiring administrator with a new token.
func recoverAdministrator(ctx context.Context, args []string) error {
	configPath, name := config.DefaultServerPath, "recovery-admin"
	flags := flag.NewFlagSet("recover-admin", flag.ContinueOnError)
	flags.StringVar(&configPath, "config", configPath, "server configuration path")
	flags.StringVar(&name, "name", name, "administrator account to create or restore")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 {
		return errors.New("recover-admin accepts no positional arguments")
	}
	name = strings.TrimSpace(name)
	if name == "" || len(name) > 128 || !utf8.ValidString(name) {
		return errors.New("--name must be 1-128 bytes of valid UTF-8")
	}
	loaded, err := config.LoadServer(configPath)
	if err != nil {
		return err
	}
	server := newServer(loaded, "provisioning")
	if err := server.openMaintenanceDatabase(ctx, os.Stdin, os.Stderr); err != nil {
		return err
	}
	defer closeProvisioningDatabase(server)
	storeContext, cancel := context.WithTimeout(ctx, storeOperationTimeout)
	defer cancel()
	account, token, err := server.store.RestoreAdministrator(storeContext, name, time.Now().UTC())
	if err != nil {
		return fmt.Errorf("restore administrator: %w", err)
	}
	fmt.Fprintf(os.Stderr, "> Administrator %q restored; earlier tokens for this account no longer work.\n", account.Name)
	fmt.Fprintln(os.Stderr, "> Store this administrator token now; it will not be shown again.")
	fmt.Fprintln(os.Stdout, token)
	return nil
}

// closeProvisioningDatabase releases store resources after a one-shot command
// and returns the database files to the service account. chown -h never follows
// a symlink: that account controls the state directory, and root must not act on
// whatever it points a database file name at.
func closeProvisioningDatabase(s *Server) {
	_ = s.store.Close()
	for _, path := range []string{s.config.Server.Database, s.config.Server.Database + "-wal", s.config.Server.Database + "-shm"} {
		if _, err := os.Lstat(path); err == nil {
			_, _ = provisioning.Run("", "chown", "-h", "neodse-server:neodse-server", path)
		}
	}
}

// removeWGPeer removes exactly one managed peer block and rejects malformed nesting.
func removeWGPeer(contents, agentID string) (string, error) {
	scanner := bufio.NewScanner(strings.NewReader(contents))
	beginPrefix := "# NeoDSEAgentBegin = "
	endPrefix := "# NeoDSEAgentEnd = "
	var lines []string
	blockID := ""
	for scanner.Scan() {
		line := scanner.Text()
		trimmed := strings.TrimSpace(line)
		if beginID, ok := strings.CutPrefix(trimmed, beginPrefix); ok {
			if blockID != "" {
				return "", errors.New("WireGuard configuration contains nested NeoDSE peer blocks")
			}
			blockID = strings.TrimSpace(beginID)
			if !identity.ValidAgentID(blockID) {
				return "", errors.New("WireGuard configuration contains an invalid NeoDSE peer identifier")
			}
			if blockID != agentID {
				lines = append(lines, line)
			}
			continue
		}
		if endID, ok := strings.CutPrefix(trimmed, endPrefix); ok {
			endID = strings.TrimSpace(endID)
			if blockID == "" || endID != blockID {
				return "", errors.New("WireGuard configuration contains an unmatched NeoDSE peer block")
			}
			if blockID != agentID {
				lines = append(lines, line)
			}
			blockID = ""
			continue
		}
		if blockID != agentID {
			lines = append(lines, line)
		}
	}
	if err := scanner.Err(); err != nil {
		return "", err
	}
	if blockID != "" {
		return "", errors.New("WireGuard configuration contains an unterminated NeoDSE peer block")
	}
	return strings.TrimRight(strings.Join(lines, "\n"), "\n") + "\n", nil
}
